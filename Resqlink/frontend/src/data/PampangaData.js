/**
 * Detects the closest ResQLink Municipality and Barangay with high accuracy
 */
export function getNearestResqlinkTown(lat, lng) {
  if (!lat || !lng) return { town: 'Porac', barangay: 'Poblacion' };

  let closestTown = 'Santa Rita';
  let closestBrgy = 'San Basilio';
  let minDistance = Infinity;

  // Search through all barangays in all 3 municipalities for the nearest point
  for (const [town, brgyMap] of Object.entries(RESQLINK_BARANGAY_COORDS)) {
    for (const [brgyName, coords] of Object.entries(brgyMap)) {
      const d = Math.sqrt(Math.pow(lat - coords.lat, 2) + Math.pow(lng - coords.lng, 2));
      if (d < minDistance) {
        minDistance = d;
        closestTown = town;
        closestBrgy = brgyName;
      }
    }
  }

  return { town: closestTown, barangay: closestBrgy };
}

/**
 * Geocodes Pampanga town, barangay, and landmark to Latitude / Longitude coordinates
 */
export function geocodePampangaAddress(town, barangay = '', street = '') {
  // Check exact ResQLink barangay coordinates first
  if (RESQLINK_BARANGAY_COORDS[town]?.[barangay]) {
    return RESQLINK_BARANGAY_COORDS[town][barangay];
  }

  const baseCoords = RESQLINK_TOWN_CENTERS[town] || PAMPANGA_COORDINATES[town] || { lat: 15.0719, lng: 120.5419 };
  if (!barangay) return baseCoords;

  const barangays = PAMPANGA_BARANGAYS_MAP[town] || [];
  const brgyIndex = barangays.indexOf(barangay);

  if (brgyIndex === -1) return baseCoords;

  const latOffset = ((brgyIndex % 5) - 2) * 0.003;
  const lngOffset = (Math.floor(brgyIndex / 5) - 2) * 0.003;

  return {
    lat: parseFloat((baseCoords.lat + latOffset).toFixed(6)),
    lng: parseFloat((baseCoords.lng + lngOffset).toFixed(6)),
  };
}

/**
 * Intelligently detects the exact Pampanga Town from address text, landmark, or city field
 */
export function detectPampangaTown(address = '', city = '', fallback = 'Porac') {
  const towns = [
    'Santa Rita', 'Guagua', 'Porac', 'City of San Fernando', 'Angeles City', 'Mabalacat City',
    'Floridablanca', 'Lubao', 'Mexico', 'Arayat', 'Apalit', 'Candaba', 'Bacolor', 'Macabebe',
    'Masantol', 'Minalin', 'San Luis', 'San Simon', 'Santa Ana', 'Santo Tomas', 'Sasmuan'
  ];

  const str = `${address} ${city}`.toLowerCase();
  if (str.includes('santa rita') || str.includes('sta. rita') || str.includes('starita') || str.includes('san basilio') || str.includes('becuran') || str.includes('dila dila')) {
    return 'Santa Rita';
  }
  if (str.includes('guagua') || str.includes('pulungmasle') || str.includes('ascomo') || str.includes('bancal')) {
    return 'Guagua';
  }
  if (str.includes('porac') || str.includes('cangatba') || str.includes('manibaug') || str.includes('pulung santol') || str.includes('inararo')) {
    return 'Porac';
  }

  for (const t of towns) {
    if (str.includes(t.toLowerCase())) {
      return t;
    }
  }

  return fallback;
}

